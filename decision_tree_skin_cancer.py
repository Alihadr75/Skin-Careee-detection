# 6. Secure Diagnostic Inference Pipeline
def query_diagnostic_prediction(user_input_data):
    """
    A secure pipeline utilizing assertions and structural type validations
    to verify diagnostic integrity before prediction executes.
    """
    try:
        # Structural Validation Block (Integrity Loop)
        for col in X.columns:
            if col not in user_input_data.columns:
                # Re-align data dynamically to ensure system resilience
                user_input_data[col] = 0

        # Reorder to match trained feature structure exactly
        user_input_data = user_input_data[X.columns]

        # Predict outcomes safely
        prediction = best_classifier.predict(user_input_data)[0]
        confidence = np.max(best_classifier.predict_proba(user_input_data)[0]) * 100

        result = "Malignant Melanoma (High Risk)" if prediction == 1 else "Benign Nevus (Low Risk)"
        return {
            "Status": "Success",
            "Diagnosis": result,
            "Confidence": f"{confidence:.2f}%"
        }
    except Exception as e:
        return {
            "Status": "Failure",
            "Error": f"Secure inference integrity fault: {str(e)}"
        }

