import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, accuracy_score, confusion_matrix

# 1. Generate a high-fidelity synthetic clinical dataset mimicking ISIC features
np.random.seed(42)
n_samples = 500

data = {
    'age': np.random.normal(52, 15, n_samples).astype(int),
    'anatom_site': np.random.choice(['torso', 'lower extremity', 'upper extremity', 'head/neck', 'palms/soles'], n_samples),
    'sex': np.random.choice(['male', 'female'], n_samples, p=[0.52, 0.48]),
    'asymmetry': np.random.randint(0, 2, n_samples),
    'border_irregularity': np.random.randint(0, 2, n_samples),
    'color_variation': np.random.randint(0, 2, n_samples),
    'diameter_mm': np.random.normal(6.5, 3, n_samples).clip(1, 25),
    'evolution': np.random.randint(0, 2, n_samples)
}

df = pd.DataFrame(data)

# Calculate a diagnostic target score mimicking melanoma risk
risk_score = (df['asymmetry'] * 1.5 +
              df['border_irregularity'] * 1.5 +
              df['color_variation'] * 1.5 +
              df['evolution'] * 2.0 +
              (df['diameter_mm'] > 6.0).astype(int) * 1.5 +
              (df['age'] > 60).astype(int) * 1.0)

# Target label: 1 = Malignant Melanoma, 0 = Benign Nevus
df['target'] = (risk_score >= 4.5).astype(int)

print("--- Dataset successfully initialized ---")
print(df.head())

